// runs in the page: a twisting ribbon of fine lines in the accent blues. it
// enters the top screen from the left and pinches, crosses the bezel to the
// main screen wide open, pinches again on its right side and thins to a
// thread across the portrait screen's bottom corner, clear of the terminal
const drawRoom = ({ accent, accentDeep, pxPerMm, px, preview, screens }) => {
  const canvas = document.createElement("canvas");
  const ctx = canvas.getContext("2d");

  canvas.width = px.width;
  canvas.height = px.height;
  ctx.fillStyle = "#000";
  ctx.fillRect(0, 0, px.width, px.height);

  const smooth = (edge0, edge1, value) => {
    const t = Math.min(1, Math.max(0, (value - edge0) / (edge1 - edge0)));

    return t * t * (3 - 2 * t);
  };
  // catmull-rom through the ribbon's path, in mm (the first and last points
  // only steer the ends)
  const path = [
    [-220, 40],
    [-60, 92],
    [190, 172],
    [370, 300],
    [470, 440],
    [560, 540],
    [680, 600],
    [770, 710],
    [900, 880],
  ];
  const at = (t) => {
    const scaled = Math.min(0.9999, Math.max(0, t)) * (path.length - 3);
    const i = Math.floor(scaled) + 1;
    const u = scaled - (i - 1);
    const [p0, p1, p2, p3] = [path[i - 1], path[i], path[i + 1], path[i + 2]];

    return [0, 1].map(
      (axis) =>
        0.5 *
        (2 * p1[axis] +
          (p2[axis] - p0[axis]) * u +
          (2 * p0[axis] - 5 * p1[axis] + 4 * p2[axis] - p3[axis]) * u * u +
          (3 * p1[axis] - p0[axis] - 3 * p2[axis] + p3[axis]) * u * u * u)
    );
  };
  const STEPS = 900;
  const LINES = 34;
  const centre = Array.from({ length: STEPS + 1 }, (_, step) =>
    at(step / STEPS)
  );
  const normals = centre.map((point, step) => {
    const [ax, ay] = centre[Math.max(0, step - 1)];
    const [bx, by] = centre[Math.min(STEPS, step + 1)];
    const length = Math.hypot(bx - ax, by - ay) || 1;

    return [-(by - ay) / length, (bx - ax) / length];
  });
  // the ribbon pinches on the top screen, crosses to the main screen wide
  // open, pinches again and thins to a thread before the portrait screen
  const lineAt = (u, step) => {
    const t = step / STEPS;
    const envelope =
      t < 0.4
        ? 0.45 + 0.55 * smooth(0, 0.4, t)
        : 1 - 0.94 * smooth(0.4, 0.9, t);
    const halfWidth = 78 * envelope;
    const twist = 0.08 + 7.5 * t;
    const offset =
      halfWidth * (u * Math.cos(twist) + 0.14 * Math.sin(twist + u * 1.7));
    const [x, y] = centre[step];
    const [nx, ny] = normals[step];

    return [x + nx * offset, y + ny * offset];
  };
  const [startX, startY] = at(0);
  const [endX, endY] = at(0.97);
  const gradient = (alpha) => {
    const fill = ctx.createLinearGradient(startX, startY, endX, endY);

    fill.addColorStop(0, `hsla(${accentDeep} / ${alpha * 0.35})`);
    fill.addColorStop(0.2, `hsla(${accentDeep} / ${alpha * 0.85})`);
    fill.addColorStop(0.45, `hsla(${accent} / ${alpha})`);
    fill.addColorStop(0.75, `hsla(${accent} / ${alpha * 0.7})`);
    fill.addColorStop(1, `hsla(${accent} / 0)`);

    return fill;
  };
  const strokeLines = (target, width, alpha) => {
    target.lineCap = "round";
    target.lineJoin = "round";
    target.lineWidth = width;

    for (let line = 0; line < LINES; line += 1) {
      const u = -1 + (2 * line) / (LINES - 1);

      target.strokeStyle = gradient(alpha * (1 - 0.65 * Math.abs(u)));
      target.beginPath();

      for (let step = 0; step <= STEPS; step += 1) {
        const [x, y] = lineAt(u, step);

        if (step === 0) target.moveTo(x, y);
        else target.lineTo(x, y);
      }

      target.stroke();
    }
  };

  ctx.setTransform(pxPerMm, 0, 0, pxPerMm, 0, 0);

  // a faint deep blue haze at the pinch and where the ribbon crosses the
  // bezel, kept tight so most of the room stays true black
  ctx.globalCompositeOperation = "lighter";
  [
    [215, 185, 110, 0.12],
    [420, 360, 150, 0.08],
  ].forEach(([x, y, radius, alpha]) => {
    const haze = ctx.createRadialGradient(x, y, 0, x, y, radius);

    haze.addColorStop(0, `hsla(${accentDeep} / ${alpha})`);
    haze.addColorStop(0.55, `hsla(${accentDeep} / ${alpha * 0.35})`);
    haze.addColorStop(1, `hsla(${accentDeep} / 0)`);
    ctx.fillStyle = haze;
    ctx.fillRect(x - radius, y - radius, radius * 2, radius * 2);
  });

  // glow: the lines drawn wide on their own layer, blurred and added on top
  const glow = document.createElement("canvas");
  const glowCtx = glow.getContext("2d");

  glow.width = px.width;
  glow.height = px.height;
  glowCtx.setTransform(pxPerMm, 0, 0, pxPerMm, 0, 0);
  strokeLines(glowCtx, 1.6, 0.2);
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  ctx.filter = `blur(${Math.round(4 * pxPerMm)}px)`;
  ctx.drawImage(glow, 0, 0);
  ctx.filter = "none";
  ctx.setTransform(pxPerMm, 0, 0, pxPerMm, 0, 0);
  strokeLines(ctx, 0.36, 0.78);
  ctx.globalCompositeOperation = "source-over";
  ctx.setTransform(1, 0, 0, 1, 0, 0);

  // a little noise on anything lit, so the soft falloff doesn't band;
  // true black stays true black
  const image = ctx.getImageData(0, 0, px.width, px.height);
  const { data } = image;
  let seed = 7;

  for (let i = 0; i < data.length; i += 4) {
    if (data[i] + data[i + 1] + data[i + 2] > 6) {
      seed = (Math.imul(seed, 1103515245) + 12345) & 0x7fffffff;

      const noise = (seed / 0x7fffffff - 0.5) * 2.4;

      data[i] = Math.max(1, data[i] + noise);
      data[i + 1] = Math.max(1, data[i + 1] + noise);
      data[i + 2] = Math.max(1, data[i + 2] + noise);
    }
  }

  ctx.putImageData(image, 0, 0);

  const result = { image: canvas.toDataURL("image/webp", 0.86) };

  if (preview) {
    // the room as seen: bezels in dark grey, a third of the size
    const scale = 1 / 3;
    const room = document.createElement("canvas");
    const roomCtx = room.getContext("2d");

    room.width = Math.round(px.width * scale);
    room.height = Math.round(px.height * scale);
    roomCtx.fillStyle = "#1b1d21";
    roomCtx.fillRect(0, 0, room.width, room.height);
    Object.values(screens).forEach(({ rect: [x, y, width, height] }) => {
      const k = pxPerMm * scale;

      roomCtx.drawImage(
        canvas,
        x * pxPerMm,
        y * pxPerMm,
        width * pxPerMm,
        height * pxPerMm,
        x * k,
        y * k,
        width * k,
        height * k
      );
    });
    result.preview = room.toDataURL("image/png");
  }

  return result;
};

const writeDataUrl = (file, dataUrl) => {
  const bytes = Buffer.from(dataUrl.split(",")[1], "base64");

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, bytes);

  return bytes.length;
};

const main = async () => {
  const args = process.argv.slice(2);
  const previewIndex = args.indexOf("--preview");
  const preview = previewIndex === -1 ? "" : resolve(args[previewIndex + 1]);
  const theme = buildTheme();

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(
    join(OUT_DIR, THEME_FILE),
    `${JSON.stringify(theme, null, 2)}\n`
  );
  console.info(`wrote public/embed/${THEME_FILE}`);

  if (args.includes("--theme-only")) return;

  const { chromium } = require("playwright-core");
  const browser = await chromium.launch();

  try {
    const page = await browser.newPage();
    const hslParts = (css) =>
      css
        .match(/[\d.]+%?/g)
        .slice(0, 3)
        .join(" ");
    const result = await page.evaluate(drawRoom, {
      accent: hslParts(theme.colors.accent),
      accentDeep: hslParts(theme.colors.accentDeep),
      preview: Boolean(preview),
      px: theme.span.px,
      pxPerMm: PX_PER_MM,
      screens: SCREENS,
    });
    const size = writeDataUrl(join(OUT_DIR, IMAGE_FILE), result.image);

    console.info(
      `wrote public/embed/${IMAGE_FILE} (${theme.span.px.width} x ${theme.span.px.height}, ${Math.round(size / 1024)} KB)`
    );

    if (size > MAX_IMAGE_BYTES) {
      throw new Error(`${IMAGE_FILE} is over ${MAX_IMAGE_BYTES / 1024} KB`);
    }

    if (preview) {
      writeDataUrl(preview, result.preview);
      console.info(`wrote ${preview}`);
    }
  } finally {
    await browser.close();
  }
};

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
