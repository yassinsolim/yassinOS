// builds the kit yassin.app's room uses around the embedded desktop:
//   public/embed/room-theme.json  yassinOS's look, the span image and the screen layout
//   public/embed/room-span.webp   one wallpaper spanning the room's three screens
//
// node scripts/roomSpan.js                  theme and image
// node scripts/roomSpan.js --theme-only     just the theme
// node scripts/roomSpan.js --preview a.png  also a small preview with the bezels drawn in
//
// the image is drawn on a canvas in playwright's chromium
// (`yarn playwright install chromium` if it's missing)

const { existsSync, mkdirSync, readFileSync, writeFileSync } = require("fs");
const { dirname, join, resolve } = require("path");
const ts = require("typescript");

const ROOT = resolve(__dirname, "..");
const OUT_DIR = join(ROOT, "public/embed");
const IMAGE_FILE = "room-span.webp";
const THEME_FILE = "room-theme.json";
const MAX_IMAGE_BYTES = 400 * 1024;
const PX_PER_MM = 3;

// the room in millimetres, x right and y down from the top left corner
const ROOM_MM = { width: 976.4, height: 705.4 };
const SCREENS = {
  M1: {
    display: "main",
    content: "yassinOS",
    css: { width: 1600, height: 900 },
    rect: [0, 369.7, 596.7, 335.7],
  },
  M2: { display: "top", content: "widgets", rect: [0, 0, 596.7, 335.7] },
  M3: {
    display: "right",
    content: "terminal",
    orientation: "portrait",
    rect: [640.7, 56.35, 335.7, 596.7],
  },
};

// loads a module from the app's typescript sources, with paths from the repo
// root like tsconfig's baseUrl, so the theme values are the real ones
const STUBS = {
  "next/dynamic": { __esModule: true, default: () => () => null },
};
const loaded = new Map();

const loadSource = (request) => {
  if (STUBS[request]) return STUBS[request];

  const file = [".ts", ".tsx", "/index.ts"]
    .map((extension) => join(ROOT, `${request}${extension}`))
    .find((path) => existsSync(path));

  if (!file) return require(request);

  if (!loaded.has(file)) {
    const module = { exports: {} };
    const { outputText } = ts.transpileModule(readFileSync(file, "utf8"), {
      compilerOptions: {
        esModuleInterop: true,
        jsx: ts.JsxEmit.ReactJSX,
        module: ts.ModuleKind.CommonJS,
        target: ts.ScriptTarget.ES2022,
      },
      fileName: file,
    });

    loaded.set(file, module);
    new Function("exports", "require", "module", outputText)(
      module.exports,
      loadSource,
      module
    );
  }

  return loaded.get(file).exports;
};

const round = (value, digits = 6) => Number(value.toFixed(digits));

const hslToHex = (css) => {
  const [h, s, l] = css
    .match(/[\d.]+/g)
    .slice(0, 3)
    .map(Number);
  const saturation = s / 100;
  const lightness = l / 100;
  const chroma = saturation * Math.min(lightness, 1 - lightness);
  const channel = (n) => {
    const k = (n + h / 30) % 12;
    const value = lightness - chroma * Math.max(-1, Math.min(k - 3, 9 - k, 1));

    return Math.round(value * 255)
      .toString(16)
      .padStart(2, "0")
      .toUpperCase();
  };

  return `#${channel(0)}${channel(8)}${channel(4)}`;
};

const toRect = ([x, y, width, height]) => ({ x, y, width, height });

